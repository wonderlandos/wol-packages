//! `wol-port plan`: the FreeBSD build script for a recipe.
use crate::recipe::Recipe;

use crate::recipe::System;
use std::fmt::Write;

/// Single-quoted for sh (recipe validation forbids `'` and control characters).
fn q(s: &str) -> String {
    format!("'{s}'")
}

fn quoted(v: &[String]) -> String {
    v.iter().map(|o| format!(" {}", q(o))).collect()
}

/// Every pkg the build needs: tools for the build system, recipe build and run deps.
pub fn build_packages(r: &Recipe) -> Vec<String> {
    let tools: &[&str] = match r.build.system {
        System::Meson => &["meson", "ninja"],
        System::Cmake => &["cmake", "ninja"],
        System::Cargo => &["rust"],
        System::Make | System::Autotools => &[],
    };
    let mut v: Vec<String> = ["git", "pkgconf"]
        .iter()
        .chain(tools)
        .map(|s| s.to_string())
        .chain(r.deps.build.iter().cloned())
        .chain(r.deps.run.iter().cloned())
        .collect();
    v.sort();
    v.dedup();
    v
}

/// `+MANIFEST` without its closing `"deps"` member (the script appends that).
fn manifest_head(r: &Recipe) -> String {
    let v = serde_json::json!({
        "name": r.package,
        "version": r.version,
        "origin": format!("wol/{}", r.package),
        "comment": r.summary,
        "desc": format!("{}\n\n{}\nLicense: {}", r.summary, r.homepage, r.license),
        "www": r.homepage,
        "maintainer": "wonderlandos@users.noreply.github.com",
        "prefix": "/usr/local",
        "categories": ["wol"],
        "annotations": {"wol_id": r.id},
    });
    let s = serde_json::to_string(&v).unwrap_or_default();
    format!("{},\n", &s[..s.len() - 1])
}

fn build_steps(r: &Recipe) -> String {
    let opts = quoted(&r.build.options);
    let make = r.build.make.as_deref().unwrap_or("make");
    match r.build.system {
        System::Meson => format!(
            "meson setup \"$BLD\" \"$SRC\" --prefix=/usr/local --buildtype=release{opts}\n\
             meson compile -C \"$BLD\"\n\
             meson install -C \"$BLD\" --destdir \"$STAGE\"\n"
        ),
        System::Cmake => format!(
            "cmake -S \"$SRC\" -B \"$BLD\" -G Ninja -DCMAKE_INSTALL_PREFIX=/usr/local -DCMAKE_BUILD_TYPE=Release{opts}\n\
             cmake --build \"$BLD\"\n\
             DESTDIR=\"$STAGE\" cmake --install \"$BLD\"\n"
        ),
        System::Cargo => format!(
            "cargo install --locked --no-track --path \"$SRC\" --root \"$STAGE/usr/local\"{opts}\n"
        ),
        System::Make => format!(
            "{make} -C \"$SRC\" PREFIX=/usr/local{opts}\n\
             {make} -C \"$SRC\" PREFIX=/usr/local DESTDIR=\"$STAGE\" install\n"
        ),
        System::Autotools => format!(
            "[ -x ./configure ] || autoreconf -fi\n\
             ./configure --prefix=/usr/local{opts}\n\
             {make}\n\
             {make} DESTDIR=\"$STAGE\" install\n"
        ),
    }
}

/// POSIX sh, run as root in a FreeBSD VM from the repository root. Writes
/// `$OUT/<package>-<version>.pkg`, `.Info.json` and (when the app ships one) `.icon.png`.
pub fn plan(r: &Recipe, dir: &std::path::Path) -> String {
    let mut s = String::new();
    let base = format!("{}-{}", r.package, r.version);
    let info_dir = format!("usr/local/share/wolos/packages/{}", r.id);
    let _ = write!(
        s,
        r#"#!/bin/sh
# Generated by wol-port from {dir}: {name} {version}, native FreeBSD build.
set -eu
RECIPE={recipe}
ROOT=$(pwd)
WORK="${{WOL_WORK:-$ROOT/work}}/{package}"
OUT="${{WOL_OUT:-$ROOT/out}}"
SRC="$WORK/src"
BLD="$WORK/build"
STAGE="$WORK/stage"
rm -rf "$WORK"
mkdir -p "$WORK" "$OUT"
export ASSUME_ALWAYS_YES=yes

echo "==> dependencies"
pkg install -y {pkgs}

echo "==> source"
git clone --depth 1 --branch {tag} {git} "$SRC"
cd "$SRC"
for p in "$ROOT/$RECIPE"/patches/*.patch; do
  [ -f "$p" ] || continue
  echo "patch $p"
  patch -p1 -s < "$p"
done

echo "==> build"
export CC=cc CXX=c++ CFLAGS='-O2 -pipe -I/usr/local/include' CXXFLAGS='-O2 -pipe -I/usr/local/include' LDFLAGS='-L/usr/local/lib'
"#,
        dir = dir.display(),
        name = r.name,
        version = r.version,
        recipe = q(&dir.display().to_string()),
        package = r.package,
        pkgs = build_packages(r).join(" "),
        tag = q(&r.source.tag),
        git = q(&r.source.git),
    );
    for (k, v) in &r.build.env {
        let _ = writeln!(s, "export {k}={}", q(v));
    }
    s.push_str(&build_steps(r));
    let _ = write!(
        s,
        r#"
echo "==> stage"
[ -e "$STAGE/usr/local/{entry}" ] || {{ echo "entry usr/local/{entry} was not installed"; exit 1; }}
mkdir -p "$STAGE/{info_dir}"
cat > "$STAGE/{info_dir}/Info.json" <<'WOL_INFO'
{info}WOL_INFO
cp "$STAGE/{info_dir}/Info.json" "$OUT/{base}.Info.json"
find "$STAGE" -type f > "$WORK/files"
: > "$WORK/libs"
while read -r f; do
  file -b "$f" | grep -q '^ELF' || continue
  strip --strip-unneeded "$f" 2>/dev/null || true
  ldd "$f" 2>/dev/null | awk '$2 == "=>" {{ print $1, $3 }}' >> "$WORK/libs" || true
done < "$WORK/files"
if grep ' not$' "$WORK/libs"; then echo "libraries not found (above)"; exit 1; fi

echo "==> icon"
for i in "$STAGE/usr/local/share/icons/hicolor/256x256/apps/{icon}.png" "$STAGE/usr/local/share/icons/hicolor/512x512/apps/{icon}.png"; do
  if [ -f "$i" ]; then cp "$i" "$OUT/{base}.icon.png"; break; fi
done
svg="$STAGE/usr/local/share/icons/hicolor/scalable/apps/{icon}.svg"
if [ ! -f "$OUT/{base}.icon.png" ] && [ -f "$svg" ] && command -v rsvg-convert >/dev/null; then
  rsvg-convert -w 256 -h 256 -o "$OUT/{base}.icon.png" "$svg"
fi

echo "==> run dependencies"
{{
  printf '%s\n' {run}
  awk '{{ print $2 }}' "$WORK/libs" | sort -u | while read -r lib; do
    case "$lib" in "$STAGE"/*|/lib/*|/usr/lib/*) continue ;; esac
    nv=$(pkg which -q "$lib" 2>/dev/null) || {{ echo "no package owns $lib" >&2; continue; }}
    pkg query '%n' "$nv"
  done
}} | grep -v '^$' | grep -vx {package_q} | sort -u > "$WORK/deps"
cat "$WORK/deps"

echo "==> package"
{{
  cat <<'WOL_MANIFEST'
{head}WOL_MANIFEST
  printf '"deps": {{'
  sep=''
  while read -r d; do
    set -- $(pkg query '%n %o %v' "$d")
    [ $# -eq 3 ] || {{ echo "dependency $d is not installed" >&2; exit 1; }}
    printf '%s"%s": {{"origin": "%s", "version": "%s"}}' "$sep" "$1" "$2" "$3"
    sep=', '
  done < "$WORK/deps"
  printf '}}\n}}\n'
}} > "$WORK/+MANIFEST"
(cd "$STAGE" && find . \( -type f -o -type l \) | sed 's|^\.||' | sort) > "$WORK/plist"
pkg create -r "$STAGE" -M "$WORK/+MANIFEST" -p "$WORK/plist" -o "$OUT"
P="$OUT/{base}.pkg"
ls -l "$P"

echo "==> smoke test: install like wol-admind, check libraries, remove"
deps=$(pkg query -F "$P" '%dn')
[ -z "$deps" ] || pkg install -y -A $deps
pkg add "$P"
pkg info -l {package_q} | head -n 20
if file -b "/usr/local/{entry}" | grep -q '^ELF'; then
  if ldd "/usr/local/{entry}" | grep 'not found'; then echo "missing libraries"; exit 1; fi
fi
pkg add "$P" || echo "pkg add of the installed version: exit $?"
pkg add -f "$P" || echo "pkg add -f: exit $?"
pkg delete -y {package_q}
echo "==> built $P"
"#,
        entry = r.entry,
        info_dir = info_dir,
        info = r.info_json(),
        base = base,
        icon = r.icon,
        run = if r.deps.run.is_empty() {
            "''".to_string()
        } else {
            r.deps
                .run
                .iter()
                .map(|d| q(d))
                .collect::<Vec<_>>()
                .join(" ")
        },
        package_q = q(&r.package),
        head = manifest_head(r),
    );
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::recipe::System;

    fn raider() -> Recipe {
        Recipe::parse(include_str!("../tests/fixtures/raider.toml")).unwrap()
    }

    fn sh_syntax_ok(script: &str) -> bool {
        use std::io::Write;
        let mut c = std::process::Command::new("sh")
            .arg("-n")
            .stdin(std::process::Stdio::piped())
            .spawn()
            .unwrap();
        c.stdin
            .take()
            .unwrap()
            .write_all(script.as_bytes())
            .unwrap();
        c.wait().unwrap().success()
    }

    #[test]
    fn meson_script_has_every_step() {
        let r = raider();
        let s = plan(&r, std::path::Path::new("recipes/raider"));
        for want in [
            "#!/bin/sh\n",
            "set -eu\n",
            "pkg install -y git gtk4 libadwaita meson ninja pkgconf\n",
            "git clone --depth 1 --branch 'v3.1.0' 'https://github.com/ADBeveridge/raider.git' \"$SRC\"\n",
            "patch -p1 -s < \"$p\"",
            "meson setup \"$BLD\" \"$SRC\" --prefix=/usr/local --buildtype=release '-Dfoo=bar'\n",
            "meson install -C \"$BLD\" --destdir \"$STAGE\"\n",
            "export CC=cc CXX=c++",
            "export WOL_TEST='a b'\n",
            "share/wolos/packages/io.github.adbeveridge.Raider/Info.json",
            &format!("<<'WOL_INFO'\n{}WOL_INFO\n", r.info_json()),
            "pkg which -q",
            "pkg create -r \"$STAGE\" -M \"$WORK/+MANIFEST\" -p \"$WORK/plist\" -o \"$OUT\"\n",
            "\"origin\":\"wol/raider\"",
            "\"prefix\":\"/usr/local\"",
            "pkg query -F \"$P\" '%dn'",
            "pkg delete -y 'raider'\n",
        ] {
            assert!(s.contains(want), "missing {want:?} in\n{s}");
        }
        assert!(sh_syntax_ok(&s), "{s}");
    }

    #[test]
    fn build_steps_per_system() {
        let cases = [
            (
                System::Cmake,
                None,
                "cmake -S \"$SRC\" -B \"$BLD\" -G Ninja",
                "cmake",
            ),
            (
                System::Cargo,
                None,
                "cargo install --locked --no-track --path \"$SRC\" --root \"$STAGE/usr/local\"",
                "rust",
            ),
            (
                System::Make,
                None,
                "make -C \"$SRC\" PREFIX=/usr/local DESTDIR=\"$STAGE\" install",
                "git",
            ),
            (
                System::Make,
                Some("gmake"),
                "gmake -C \"$SRC\" PREFIX=/usr/local",
                "gmake",
            ),
            (
                System::Autotools,
                None,
                "./configure --prefix=/usr/local",
                "git",
            ),
        ];
        for (sys, make, want, dep) in cases {
            let mut r = raider();
            r.build.system = sys;
            r.build.make = make.map(String::from);
            if let Some(m) = make {
                r.deps.build.push(m.into());
            }
            let s = plan(&r, std::path::Path::new("recipes/raider"));
            assert!(s.contains(want), "{sys:?}: {want}\n{s}");
            let install = s.lines().find(|l| l.starts_with("pkg install -y")).unwrap();
            assert!(install.split(' ').any(|w| w == dep), "{sys:?}: {install}");
            assert!(sh_syntax_ok(&s), "{sys:?}");
        }
    }
}
